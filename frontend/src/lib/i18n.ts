export const DICTS: Record<Lang, Dict> = { en, hi, te };
export const LANG_LABEL: Record<Lang, string> = { en: "English", hi: "हिन्दी", te: "తెలుగు" };

export type T = Dict;
export const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: Dict }>({
  lang: "en",
  setLang: () => {},
  t: en,
});
export const useLang = () => useContext(LangContext);

export function fill(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

export function asLang(code: string | undefined | null): Lang {
  return code === "hi" || code === "te" ? code : "en";
}
